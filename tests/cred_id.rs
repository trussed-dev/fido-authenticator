type Ids<const N: usize> = [Vec<u8>; N];
type Files = Vec<(PathBuf, Vec<u8>)>;

fn prepare_data<const N: usize>(data: &str) -> (Ids<N>, Files) {
    let (ids, fs) = data.split_once("----\n").unwrap();
    let ids: Vec<_> = ids
        .lines()
        .filter(|l| !l.starts_with("#"))
        .map(|s| hex::decode(s).unwrap())
        .collect();
    let files = prepare_fs(fs);
    (ids.try_into().unwrap(), files)
}

fn prepare_fs(data: &str) -> Vec<(PathBuf, Vec<u8>)> {
    let mut files = Vec::new();
    let mut iter = data.lines().filter(|l| !l.starts_with("#"));
    while let Some(path) = iter.next() {
        let data = iter.next().unwrap();
        files.push((path.try_into().unwrap(), hex::decode(data).unwrap()));
    }
    files
}

#[test]
fn test_non_discoverable() {
    let ([id], files) = prepare_data(DATA_NON_DISCOVERABLE);
    let options = Options {
        firmware_version: Some(FirmwareVersion {
            default: 0,
            credential_id_v1: Some(1),
            credential_id_v2: Some(2),
        }),
        credential_id_version: CredentialIdVersion::V2,
        user_presence: Level::Strong,
        files,
        ..Options::default()
    };
    let rp = RP1;
    virt::run_ctap2_with_options(options, |device| {
        assert_eq!(get_firmware_version(&device), 1);
        get_assertion(&device, rp, Some(&id)).unwrap();

        let mut authenticator = Authenticator::new(device).assume_pin(PIN);
        let rps = authenticator.list_rps();
        assert_eq!(rps, vec![]);
        let device = authenticator.release();

        reset(&device);

        assert_eq!(get_firmware_version(&device), 2);
        get_assertion(&device, rp, Some(&id)).err().unwrap();

        let mut authenticator = Authenticator::new(device).set_pin(PIN);
        let rps = authenticator.list_rps();
        assert_eq!(rps, vec![]);
    });
}

#[test]
fn test_discoverable() {
    let ([id], files) = prepare_data(DATA_DISCOVERABLE);
    let options = Options {
        firmware_version: Some(FirmwareVersion {
            default: 0,
            credential_id_v1: Some(1),
            credential_id_v2: Some(2),
        }),
        credential_id_version: CredentialIdVersion::V2,
        user_presence: Level::Strong,
        files,
        ..Options::default()
    };
    let rp = RP1;
    let user = USER1;
    virt::run_ctap2_with_options(options, |device| {
        assert_eq!(get_firmware_version(&device), 1);
        get_assertion(&device, rp, None).unwrap();
        get_assertion(&device, rp, Some(&id)).unwrap();

        let mut authenticator = Authenticator::new(device).assume_pin(PIN);
        let rps = authenticator.list_rps();
        assert_eq!(rps, vec![Rp::new(rp)]);
        let credentials = authenticator.list_credentials(rp);
        assert_eq!(credentials.len(), 1);
        assert_eq!(credentials[0].0.id, user);
        assert_eq!(credentials[0].1.id, id);
        let device = authenticator.release();

        reset(&device);

        assert_eq!(get_firmware_version(&device), 2);
        get_assertion(&device, rp, None).err().unwrap();
        get_assertion(&device, rp, Some(&id)).err().unwrap();

        let mut authenticator = Authenticator::new(device).set_pin(PIN);
        let rps = authenticator.list_rps();
        assert_eq!(rps, vec![]);
    });
}

#[test]
fn test_multi() {
    let ([id1, id2, id3, id4], files) = prepare_data(DATA_MULTI);
    let options = Options {
        firmware_version: Some(FirmwareVersion {
            default: 0,
            credential_id_v1: Some(1),
            credential_id_v2: Some(2),
        }),
        credential_id_version: CredentialIdVersion::V2,
        user_presence: Level::Strong,
        files,
        ..Options::default()
    };
    let cases: &[(&str, Option<&[u8]>)] = &[
        (RP1, None),
        (RP1, Some(&id1)),
        (RP1, Some(&id2)),
        (RP2, Some(&id3)),
        (RP2, Some(&id4)),
    ];
    virt::run_ctap2_with_options(options, |device| {
        assert_eq!(get_firmware_version(&device), 1);
        for &(rp, cred_id) in cases {
            get_assertion(&device, rp, cred_id).unwrap();
        }

        let mut authenticator = Authenticator::new(device).assume_pin(PIN);
        let rps = authenticator.list_rps();
        assert_eq!(rps, vec![Rp::new(RP1)]);
        let credentials = authenticator.list_credentials(RP1);
        assert_eq!(credentials.len(), 1);
        assert_eq!(credentials[0].0.id, USER2);
        assert_eq!(credentials[0].1.id, id2);
        let device = authenticator.release();

        let id5 = make_credential(&device, RP1, USER3, true, Some(PIN));
        get_assertion(&device, RP1, Some(&id5)).unwrap();

        let id6 = make_credential(&device, RP1, USER3, true, Some(PIN));
        get_assertion(&device, RP1, Some(&id6)).unwrap();

        let mut authenticator = Authenticator::new(device).assume_pin(PIN);
        let rps = authenticator.list_rps();
        assert_eq!(rps, vec![Rp::new(RP1)]);
        let credentials = authenticator.list_credentials(RP1);
        assert_eq!(credentials.len(), 2);
        for (user, credential) in credentials {
            if user.id == USER2 {
                assert_eq!(credential.id, id2);
            } else if user.id == USER3 {
                assert_eq!(credential.id, id6);
            } else {
                panic!("Unexpected user: {user:?}");
            }
        }
        let device = authenticator.release();

        reset(&device);

        assert_eq!(get_firmware_version(&device), 2);
        for &(rp, cred_id) in cases {
            get_assertion(&device, rp, cred_id).err().unwrap();
        }
        get_assertion(&device, RP1, Some(&id5)).err().unwrap();
        get_assertion(&device, RP1, Some(&id6)).err().unwrap();

        let mut authenticator = Authenticator::new(device).set_pin(PIN);
        let rps = authenticator.list_rps();
        assert_eq!(rps, vec![]);
    });
}
