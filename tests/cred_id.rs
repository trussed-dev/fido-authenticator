const CLIENT_DATA_HASH: [u8; 32] = [0; 32];

const PIN: &[u8] = b"123456";
const RP1: &str = "example.com";
const RP2: &str = "test.com";
const USER1: &[u8] = &[1; 16];
const USER2: &[u8] = &[2; 16];
const USER3: &[u8] = &[3; 16];

// The following data is generated by the generate_state_* functions on v0.3.0.
// The files contain a list of credential IDs and a list of files on the internal filesystem,
// separated by ----. See the prepare_data function for the details of the format. DATA_X is read
// from data/cred_id/x.txt, generated by generate_state_x and used by test_x.
const DATA_DISCOVERABLE: &str = include_str!("data/cred_id/discoverable.txt");
const DATA_NON_DISCOVERABLE: &str = include_str!("data/cred_id/non_discoverable.txt");
const DATA_MULTI: &str = include_str!("data/cred_id/multi.txt");

fn reset(device: &Ctap2) {
    device.exec(Reset).unwrap();
}

fn get_firmware_version(device: &Ctap2) -> usize {
    device.exec(GetInfo).unwrap().firmware_version.unwrap()
}

fn make_credential(device: &Ctap2, rp: &str, user: &[u8], rk: bool, pin: Option<&[u8]>) -> Vec<u8> {
    let pin_auth = pin.map(|pin| {
        let key_agreement_key = KeyAgreementKey::generate();
        let shared_secret = get_shared_secret(device, &key_agreement_key);
        let pin_token =
            get_pin_token(device, &key_agreement_key, &shared_secret, pin, 0x01, None).unwrap();
        pin_token.authenticate(&CLIENT_DATA_HASH)
    });
    let mut request = MakeCredential::new(
        CLIENT_DATA_HASH,
        Rp::new(rp),
        User::new(user),
        vec![PubKeyCredParam::new("public-key", -7)],
    );
    if rk {
        request.options = Some(MakeCredentialOptions::default().rk(true));
    }
    if let Some(pin_auth) = pin_auth {
        request.pin_auth = Some(pin_auth);
        request.pin_protocol = Some(2);
    }
    let response = device.exec(request).unwrap();
    response.auth_data.credential.unwrap().id
}

fn get_assertion(device: &Ctap2, rp: &str, cred_id: Option<&[u8]>) -> Result<(), Ctap2Error> {
    let mut request = GetAssertion::new(rp.to_owned(), vec![0u8; 32]);
    if let Some(cred_id) = cred_id {
        request.allow_list = Some(vec![PubKeyCredDescriptor::new(
            "public-key",
            cred_id.to_owned(),
        )]);
    }
    device.exec(request)?;
    Ok(())
}

fn generate_state<F: FnOnce(Ctap2) + Send>(f: F) {
    fn print_file(fs: &dyn DynFilesystem, path: &Path) {
        let data = fs
            .open_file_and_then(path, &mut |file| {
                let n = file.len()?;
                let mut data = vec![0; n];
                file.read_exact(&mut data)?;
                Ok(data)
            })
            .unwrap();
        println!("{path}");
        println!("{}", hex::encode(&data));
    }

    fn print_dir(fs: &dyn DynFilesystem, path: &Path) {
        let entries: Vec<_> = fs
            .read_dir_and_then(path, &mut |iter| iter.collect::<Result<_, _>>())
            .unwrap();
        for entry in entries {
            if entry.file_name() == "." || entry.file_name() == ".." {
                continue;
            }
            match entry.file_type() {
                FileType::Dir => print_dir(fs, entry.path()),
                FileType::File => print_file(fs, entry.path()),
            }
        }
    }

    fn print_fs(fs: &dyn DynFilesystem) {
        println!("----");
        print_dir(fs, path!("/"))
    }

    let options = Options {
        inspect_ifs: Some(Box::new(print_fs)),
        ..Options::default()
    };
    virt::run_ctap2_with_options(options, |device| {
        let key_agreement_key = KeyAgreementKey::generate();
        let shared_secret = get_shared_secret(&device, &key_agreement_key);
        set_pin(&device, &key_agreement_key, &shared_secret, PIN).unwrap();

        f(device)
    });
}

